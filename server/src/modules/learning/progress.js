import { getDb } from '../../db/index.js';
import { ObjectId } from 'mongodb';
import { toOid } from '../classrooms/access.js';
import { round } from '../../utils/validation.js';
import { applyMasteryEvidence } from '../intelligence/profile.js';

/**
 * LEARNING PROGRESS
 * =================
 *
 * The renderer's `progress` component and the quiz/form submissions all need
 * durable, per-student state. It lives here rather than in the renderer so that
 * a refresh, a second device or a different surface (the progress page, a
 * teacher dashboard) sees the same numbers.
 *
 * One document per (student, classroom, lesson). Lessons may be generated by an
 * ad-hoc AI tutorial with no classroom, in which case `classroomId` is null and
 * the key is (student, lesson).
 *
 * The document is deliberately small and additive so it can be written on every
 * autosave without read-modify-write races: `$set` on named fields, `$max` on
 * counters, `$addToSet` on completed ids.
 */

export const LESSON_STATUS = ['not_started', 'in_progress', 'completed'];

function lessonKey(lessonId) {
  return String(lessonId || '').slice(0, 80) || 'ad-hoc';
}

/** Upsert-and-return the progress document. */
export async function getOrCreateProgress({ userId, classroomId = null, lessonId, title = '', conceptId = null, totalComponents = 0 }) {
  const db = getDb();
  const filter = {
    userId: toOid(userId),
    classroomId: classroomId ? toOid(classroomId) : null,
    lessonId: lessonKey(lessonId),
  };
  const now = new Date();
  await db.collection('learning_progress').updateOne(
    filter,
    {
      $setOnInsert: {
        ...filter,
        title: String(title || '').slice(0, 200),
        conceptId: conceptId ? toOid(conceptId) : null,
        status: 'in_progress',
        completedComponentIds: [],
        quizzes: [],
        forms: [],
        createdAt: now,
      },
      $set: { lastActiveAt: now, updatedAt: now },
      $max: { totalComponents: Number(totalComponents) || 0 },
    },
    { upsert: true },
  );
  return db.collection('learning_progress').findOne(filter);
}

/**
 * Recompute completion from the union of every completion signal we record.
 *
 * `completedComponentIds` stores the bare component id, and `gradeQuiz` /
 * `recordFormSubmission` also `$addToSet` it. This function used to add a
 * *prefixed* copy (`quiz:<id>`, `form:<id>`) on top, so one quiz submission
 * counted as two completed sections — a nine-section lesson read 44% after a
 * form and a quiz (2 + 2 of 9) instead of 22% (2 of 9). The distinction that
 * matters is the component id alone: every signal names the same component.
 */
function deriveStatus(doc) {
  if (!doc) return 'not_started';
  const done = new Set(doc.completedComponentIds || []);
  for (const quiz of doc.quizzes || []) done.add(String(quiz.componentId));
  for (const form of doc.forms || []) done.add(String(form.componentId));
  const total = Math.max(Number(doc.totalComponents) || 0, done.size);
  const percent = total ? Math.min(100, Math.round((done.size / total) * 100)) : 0;
  return {
    doneCount: done.size,
    total,
    percent,
    status: percent >= 100 ? 'completed' : done.size > 0 ? 'in_progress' : 'not_started',
  };
}

export function serialiseProgress(doc) {
  if (!doc) return null;
  const derived = deriveStatus(doc);
  return {
    lessonId: doc.lessonId,
    classroomId: doc.classroomId ? String(doc.classroomId) : null,
    title: doc.title || '',
    conceptId: doc.conceptId ? String(doc.conceptId) : null,
    status: derived.status,
    percent: derived.percent,
    completedCount: derived.doneCount,
    totalComponents: derived.total,
    completedComponentIds: doc.completedComponentIds || [],
    quizzes: (doc.quizzes || []).slice(-20).map((q) => ({ componentId: q.componentId, score: q.score, max: q.max, correct: q.correct, at: q.at })),
    forms: (doc.forms || []).slice(-20).map((f) => ({ componentId: f.componentId, score: f.score, answered: f.answered, at: f.at })),
    lastActiveAt: doc.lastActiveAt,
  };
}

/** Record a completed section (a scrolled-through component, a step-through, etc). */
export async function markComponentComplete({ userId, classroomId = null, lessonId, title, componentId, totalComponents = 0 }) {
  const db = getDb();
  const doc = await getOrCreateProgress({ userId, classroomId, lessonId, title, totalComponents });
  await db.collection('learning_progress').updateOne(
    { _id: doc._id },
    {
      $addToSet: { completedComponentIds: String(componentId).slice(0, 64) },
      $set: { lastActiveAt: new Date(), updatedAt: new Date() },
      $max: { totalComponents: Number(totalComponents) || 0 },
    },
  );
  return serialiseProgress(await db.collection('learning_progress').findOne({ _id: doc._id }));
}

/**
 * Grade a quiz submission.
 *
 * The correct answers never leave the server before submission: the client gets
 * the questions without `correct_index`, and this function owns the comparison.
 * (The client *does* receive the answers inside the rendered document, because a
 * rendered lesson can be inspected by anyone; hiding them here is about not
 * putting the answer key in the initial API payload for a *server-stored* quiz,
 * and the route enforces the same rule for assessments.)
 */
export async function gradeQuiz({ userId, classroomId = null, lessonId, title, componentId, questions, answers, conceptId = null }) {
  const db = getDb();
  const byId = new Map((answers || []).map((a) => [String(a.question_id), Number(a.value)]));
  const results = (questions || []).map((q) => {
    const chosen = byId.get(String(q.id));
    const correct = Number.isInteger(chosen) && chosen === Number(q.correct_index);
    return {
      questionId: q.id,
      chosen: Number.isInteger(chosen) ? chosen : null,
      correctIndex: Number(q.correct_index),
      correct,
      explanation: q.explanation || '',
    };
  });
  const max = results.length;
  const correctCount = results.filter((r) => r.correct).length;
  const score = max ? round((correctCount / max) * 100, 1) : 0;

  const doc = await getOrCreateProgress({ userId, classroomId, lessonId, title });
  const attempt = { componentId: String(componentId || 'quiz').slice(0, 64), score, max, correct: correctCount, answers: results, at: new Date() };
  await db.collection('learning_progress').updateOne(
    { _id: doc._id },
    {
      $push: { quizzes: { $each: [attempt], $slice: -50 } },
      $addToSet: { completedComponentIds: attempt.componentId },
      $set: { lastActiveAt: new Date(), updatedAt: new Date() },
    },
  );

  // Quiz performance is mastery evidence, exactly like an assessment question.
  if (classroomId && conceptId) {
    await applyMasteryEvidence({
      userId,
      classroomId,
      conceptId,
      correct: max > 0 && correctCount / max >= 0.7,
      hinted: false,
      source: 'quiz',
    }).catch(() => {});
  }

  return { score, correct: correctCount, max, passing: score >= 70, results };
}

/** Record a submitted question form (used for progress, not grading). */
export async function recordFormSubmission({ userId, classroomId = null, lessonId, title, componentId, answers, evaluation = null }) {
  const db = getDb();
  const doc = await getOrCreateProgress({ userId, classroomId, lessonId, title });
  const entry = {
    componentId: String(componentId || 'form').slice(0, 64),
    answered: (answers || []).length,
    score: evaluation?.score ?? null,
    at: new Date(),
  };
  await db.collection('learning_progress').updateOne(
    { _id: doc._id },
    {
      $push: { forms: { $each: [entry], $slice: -50 } },
      $addToSet: { completedComponentIds: entry.componentId },
      $set: { lastActiveAt: new Date(), updatedAt: new Date() },
    },
  );
  return entry;
}

/** All lessons for a student, newest first. */
export async function listProgress({ userId, classroomId = null, limit = 40 }) {
  const db = getDb();
  const filter = { userId: toOid(userId), lessonId: { $ne: null } };
  if (classroomId) filter.classroomId = toOid(classroomId);
  const docs = await db.collection('learning_progress').find(filter).sort({ lastActiveAt: -1 }).limit(Math.min(100, Math.max(1, limit))).toArray();
  return docs.map(serialiseProgress);
}

/** Aggregate progress across lessons — what the progress page shows. */
export function summariseProgress(items) {
  const lessons = items.length;
  const completed = items.filter((i) => i.status === 'completed').length;
  const inProgress = items.filter((i) => i.status === 'in_progress').length;
  const quizAttempts = items.flatMap((i) => i.quizzes || []);
  const averageQuizScore = quizAttempts.length
    ? round(quizAttempts.reduce((a, q) => a + (q.score || 0), 0) / quizAttempts.length, 1)
    : null;
  const overall = lessons ? Math.round(items.reduce((a, i) => a + (i.percent || 0), 0) / lessons) : 0;
  return { lessons, completed, inProgress, quizAttempts: quizAttempts.length, averageQuizScore, overallPercent: overall };
}

/**
 * Verify a lesson belongs to the caller before mutating it.
 *
 * Progress writes are authenticated, so a caller could otherwise mark *another*
 * student's lesson complete by guessing its id. Every write route calls this
 * first.
 */
export async function requireProgressOwner({ userId, classroomId = null, lessonId }) {
  const db = getDb();
  if (!ObjectId.isValid(String(userId))) return null;
  const doc = await db.collection('learning_progress').findOne({
    userId: toOid(userId),
    classroomId: classroomId ? toOid(classroomId) : null,
    lessonId: lessonKey(lessonId),
  });
  return doc;
}

/** Delete a student's own progress for a lesson (privacy control). */
export async function clearProgress({ userId, lessonId = null }) {
  const db = getDb();
  const filter = { userId: toOid(userId) };
  if (lessonId) filter.lessonId = lessonKey(lessonId);
  const res = await db.collection('learning_progress').deleteMany(filter);
  return res.deletedCount || 0;
}
