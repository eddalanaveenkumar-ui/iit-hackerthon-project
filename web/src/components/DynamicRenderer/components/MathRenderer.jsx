import { useMemo } from 'react';
import katex from 'katex';
import 'katex/dist/katex.min.css';
import { Sigma } from 'lucide-react';
import { Body, Empty, Notice, Panel, WIDTH_CLASS } from './shared';
import { sanitizeText } from '../utils/validateUI';

/**
 * `math` — LaTeX typeset by KaTeX.
 *
 * KaTeX is configured with `trust: false` and `strict: 'warn'`: no `\href`,
 * `\url`, `\htmlClass` or `\includegraphics` can escape into the page, and a
 * malformed expression throws into the error path rather than dumping source
 * into the DOM.
 *
 * `throwOnError: false` renders a red inline error instead of crashing the whole
 * lesson — one bad formula should not blank a tutorial.
 */

const KATEX_OPTIONS = {
  throwOnError: false,
  trust: false,
  strict: 'warn',
  errorColor: '#dc2626',
  macros: {
    '\\R': '\\mathbb{R}',
  },
};

/** Render LaTeX to HTML with KaTeX's own (trusted, self-generated) output. */
export function renderLatex(latex, { displayMode = true } = {}) {
  try {
    return katex.renderToString(String(latex || '').slice(0, 4000), { ...KATEX_OPTIONS, displayMode });
  } catch {
    return '';
  }
}

export default function MathRenderer({ component }) {
  const width = WIDTH_CLASS[component.style?.width] || 'w-full';
  const html = useMemo(() => renderLatex(component.latex, { displayMode: component.display !== 'inline' }), [component.latex, component.display]);

  if (!component.latex) {
    return (
      <Panel title={component.title} className={width}>
        <Empty label="This formula is empty." icon={Sigma} />
      </Panel>
    );
  }

  // KaTeX output is generated by KaTeX from a validated string — it is the one
  // place in this renderer where injected markup is acceptable, and it contains
  // no external references or event handlers.
  const formula = html ? (
    <div
      className="overflow-x-auto py-1 text-[1.05rem] text-slate-800 dark:text-slate-100"
      // eslint-disable-next-line react/no-danger -- KaTeX-generated markup, trust:false
      dangerouslySetInnerHTML={{ __html: html }}
      role="math"
      aria-label={sanitizeText(component.latex)}
    />
  ) : (
    <Notice>The formula could not be typeset. The source is: {sanitizeText(component.latex, 200)}</Notice>
  );

  if (!component.title && !component.explanation && !component.steps?.length) {
    return <div className={width}>{formula}</div>;
  }

  return (
    <Panel title={component.title} subtitle={component.subtitle} icon={component.style?.icon || 'sigma'} className={width}>
      <div className="space-y-2.5">
        {formula}
        {component.steps?.length ? (
          <ol className="space-y-1.5 border-t border-slate-100 pt-2.5 dark:border-slate-800">
            {component.steps.map((step, index) => (
              <li key={index} className="flex flex-wrap items-baseline gap-x-2 text-sm">
                <span className="shrink-0 text-xs font-medium text-slate-500 dark:text-slate-400">
                  {index + 1}. {step.label}
                </span>
                <span
                  className="overflow-x-auto text-slate-800 dark:text-slate-100"
                  // eslint-disable-next-line react/no-danger -- KaTeX-generated markup
                  dangerouslySetInnerHTML={{ __html: renderLatex(step.latex, { displayMode: false }) }}
                  aria-label={sanitizeText(step.latex)}
                />
              </li>
            ))}
          </ol>
        ) : null}
        {component.explanation ? (
          <div className="border-t border-slate-100 pt-2 dark:border-slate-800">
            <Body>{component.explanation}</Body>
          </div>
        ) : null}
      </div>
    </Panel>
  );
}
